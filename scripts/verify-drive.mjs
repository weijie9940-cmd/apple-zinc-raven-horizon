import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {checkedUrl} from './browser-guard.mjs';
const browser=await chromium.launch({headless:true,...(process.platform==='win32'?{channel:'msedge'}:{})});
try {
 const page=await browser.newPage({viewport:{width:1280,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(checkedUrl(process.argv[2]||'http://127.0.0.1:8084/'),{waitUntil:'domcontentloaded',timeout:60000});
 await page.waitForFunction(()=>window.__machine?.ready);
 assert.equal(await page.locator('#btn-drive').count(),1,'mechanical observation entry exists');
 await page.locator('#btn-play').click();
 await page.screenshot({path:'screenshots/power-overview.png'});
 await page.locator('#btn-drive').click();await page.waitForTimeout(1000);
 assert.equal(await page.locator('#drive-panel').isVisible(),true);
 assert.equal(await page.evaluate(()=>window.__machine.getExperience().drive.timeScale),.25);
 const frozen=await page.evaluate(()=>window.__machine.getPhase());await page.waitForTimeout(200);
 assert.deepEqual(await page.evaluate(()=>window.__machine.getPhase()),frozen);
 await page.locator('#btn-drive-reveal').click();
 assert.equal(await page.evaluate(()=>window.__machine.scene.getObjectByName('drive/motor-shell').material.opacity),1);
 await page.locator('#btn-drive-reveal').click();
 assert.equal(await page.evaluate(()=>window.__machine.scene.getObjectByName('drive/motor-shell').material.opacity),.14);
 const coupling=await page.evaluate(()=>{
  const m=window.__machine,a=m.getPhase();m.audit(.2);const b=m.getPhase(),scene=m.scene;
  return {input:scene.getObjectByName('drive/input-rotor').rotation.z-b.phi1,output:scene.getObjectByName('drive/output-coupling').rotation.z-b.phi3,
   ratio:(b.phi3-a.phi3)/(b.phi1-a.phi1),reverse:(b.phi2-a.phi2)/(b.phi1-a.phi1)};
 });
 assert.ok(Math.abs(coupling.input)<1e-9&&Math.abs(coupling.output)<1e-9);
 assert.ok(Math.abs(coupling.ratio-.2)<1e-8&&Math.abs(coupling.reverse+1/3)<1e-8,JSON.stringify(coupling));
 await page.screenshot({path:'screenshots/power-motor.png'});
 await page.locator('[data-drive-step="1"]').click();await page.waitForTimeout(1000);await page.screenshot({path:'screenshots/power-gears.png'});
 await page.locator('[data-drive-step="2"]').click();await page.waitForTimeout(1000);await page.screenshot({path:'screenshots/power-shaft.png'});
 await page.locator('[data-drive-step="3"]').click();await page.waitForTimeout(1000);await page.screenshot({path:'screenshots/power-lift.png'});
 await page.locator('[data-drive-step="0"]').click();await page.waitForTimeout(1000);
 await page.locator('#btn-drive-tour').click();await page.waitForTimeout(250);
 assert.equal(await page.evaluate(()=>window.__machine.getExperience().drive.step),0,'paused tour holds its shot');
 await page.locator('#btn-drive-pause').click();
 await page.waitForFunction(()=>window.__machine.getExperience().drive.step===1,{},{timeout:12000});
 const canvas=await page.locator('#view').boundingBox();
 await page.mouse.move(canvas.x+canvas.width*.45,canvas.y+canvas.height*.55);await page.mouse.down();await page.mouse.move(canvas.x+canvas.width*.5,canvas.y+canvas.height*.55,{steps:5});await page.mouse.up();
 assert.equal(await page.evaluate(()=>window.__machine.getExperience().drive.auto),false,'drag stops automatic shots');
 await page.locator('#btn-drive-pause').click();
 await page.locator('#btn-drive-close').click();
 assert.equal(await page.evaluate(()=>window.__machine.getExperience().drive.timeScale),1);
 assert.equal(await page.evaluate(()=>window.__machine.scene.getObjectByName('drive/motor-shell').material.opacity),1);
 await page.locator('#btn-drive').click();await page.locator('#btn-routing').click();assert.equal(await page.locator('#drive-panel').isVisible(),false);
 await page.locator('#btn-routing-close').click();await page.setViewportSize({width:390,height:844});
 await page.locator('#btn-performance').click();
 await page.locator('#btn-drive').click();await page.locator('[data-drive-step="1"]').click();await page.waitForTimeout(1000);
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 const layout=await page.evaluate(()=>{const a=document.getElementById('drive-panel').getBoundingClientRect(),b=document.getElementById('view').getBoundingClientRect();return {panelBottom:a.bottom,viewTop:b.top,height:b.height};});
 assert.ok(layout.panelBottom<=layout.viewTop+1&&layout.height>200,JSON.stringify(layout));
 await page.screenshot({path:'screenshots/power-mobile.png'});
 const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
 reduced.on('pageerror',e=>errors.push(e.message));await reduced.goto(checkedUrl(process.argv[2]||'http://127.0.0.1:8084/'),{waitUntil:'domcontentloaded',timeout:60000});
 await reduced.waitForFunction(()=>window.__machine?.ready);await reduced.locator('#btn-drive').click();
 assert.equal(await reduced.locator('#btn-drive-tour').isDisabled(),true);await reduced.locator('[data-drive-step="2"]').click();
 assert.equal(await reduced.evaluate(()=>window.__machine.getExperience().drive.step),2);
 await reduced.keyboard.press('Escape');assert.equal(await reduced.locator('#drive-panel').isVisible(),false);await reduced.close();
 assert.deepEqual(errors,[]);console.log(JSON.stringify({ok:true,coupling,layout,errors}));
}finally{await browser.close();}
